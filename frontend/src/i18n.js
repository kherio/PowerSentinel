export function t(key, vars) {
  const table = DICT[LOCALE] || DICT.en;
  let str = table[key] !== undefined ? table[key] : (DICT.en[key] !== undefined ? DICT.en[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.split('{' + k + '}').join(vars[k]);
    });
  }
  return str;
}

// Walks every [data-i18n] / [data-i18n-placeholder] / [data-i18n-title]
// element in the document once at startup, filling in the static text
// that doesn't depend on any live data (labels, section titles, button
// text that's always the same, placeholders...). Dynamic text (toasts,
// generated summaries, anything with a {var}) is still produced via
// t() directly from the view modules.
export function applyStaticI18n(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = t(key);
    else el.textContent = t(key);
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
}
